
class NumberUtility {

    int getNumber() {
        // Return 10
        return 10;
    }
}

public class Main {

    public static void main(String[] args) {
        // Create object
        NumberUtility n = new NumberUtility();
        // Call getNumber()
        int g = n.getNumber();
        // Print returned value
        System.out.println(g);
    }
}
